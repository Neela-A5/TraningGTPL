#Converting Decimal number into Binary Number(0,1)
num = 25
print(bin(num))  #0b11001


#Converting Binary number into Decimal Number.
binary = 0b0101
print(binary)  #5


#Converting Decimal number into Octal Number.
num = 36
print(oct(num)) #0o44


#Converting Decimal number into HexaDecimal Number.
print(hex(num))   #0x24
print(hex(10))     #0xa
print(0xf)          #15

