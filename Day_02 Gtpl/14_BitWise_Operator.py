#Compliment Operator  (~)
print(~12)     #-13


#And Opeartor (&) both condition should be true
print(12 & 13)    # 12
print(25 & 30)      # 24


#OR Operator (|)  at least one condition is true
print(12 | 13)     # 13


#XOR Operator (^)   one condition is false, the overall result is false
print(12 ^ 13)     # 1
print(25 ^ 30)       # 7


#Left Shift(<<)
print(10 << 2)     # 40
print(7 << 1)      # 14


#Right Shift(>>)
print(10 >> 2)      # 2